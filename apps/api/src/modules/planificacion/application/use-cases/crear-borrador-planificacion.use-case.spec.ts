import { CalendarioRepository } from '../../domain/repositories/calendario.repository';
import { BadRequestException, NotFoundException } from '@nestjs/common';
import { PlanificacionRepository } from '../../domain/repositories/planificacion.repository';
import { CrearBorradorPlanificacionUseCase } from './crear-borrador-planificacion.use-case';

describe('CrearBorradorPlanificacionUseCase', () => {
  afterEach(() => {
    jest.useRealTimers();
  });

  it('should create a borrador planificacion with next version', async () => {
    // Fija la fecha del sistema dentro del periodo planificable de la
    // planificacion de prueba (2026-06): assertPeriodoPlanificable solo
    // permite el mes actual o el siguiente respecto a la fecha real.
    jest.useFakeTimers().setSystemTime(new Date('2026-06-01T12:00:00.000Z'));

    const crearBorrador = jest.fn().mockResolvedValue({
      id: 99,
      idServicio: 2,
      idDepartamento: 1,
      codigoDepartamento: 'ENF',
      nombreDepartamento: 'Enfermeria',
      codigoServicio: 'SRV-URG',
      nombreServicio: 'Urgencias',
      cantidadPersonalPlanificable: 5,
      anio: 2026,
      mes: 6,
      version: 2,
      estado: 'BORRADOR',
      activo: true,
      fechaInicio: new Date('2026-06-01T00:00:00.000Z'),
      fechaFin: new Date('2026-06-30T00:00:00.000Z'),
      fechaPublicacion: null,
      fechaCierre: null,
      createdAt: new Date('2026-05-05T00:00:00.000Z'),
      updatedAt: new Date('2026-05-05T00:00:00.000Z'),
    });

    const repository: PlanificacionRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      obtenerNombreServicio: jest.fn().mockResolvedValue('Emergencias'),
      obtenerNombreDepartamento: jest.fn().mockResolvedValue('Enfermeria'),
      existeUsuario: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnServicio: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnDepartamento: jest.fn().mockResolvedValue(true),
      existePlanificacionActivaPeriodo: jest.fn().mockResolvedValue(false),
      obtenerSiguienteVersion: jest.fn().mockResolvedValue(2),
      crearBorrador,
      cambiarEstado: jest.fn(),
      eliminarLogico: jest.fn(),
      publicar: jest.fn(),
      cerrar: jest.fn(),
    };

    const existeMes = jest.fn().mockResolvedValue(true);
    const calendarioRepository: CalendarioRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      existeMes,
      asegurarAnio: jest.fn(),
      asegurarMes: jest.fn(),
    };

    const useCase = new CrearBorradorPlanificacionUseCase(
      repository,
      calendarioRepository,
    );

    await expect(
      useCase.execute({
        idServicio: 2,
        anio: 2026,
        mes: 6,
        idUsuarioCreador: 1,
      }),
    ).resolves.toMatchObject({
      id: 99,
      idServicio: 2,
      anio: 2026,
      mes: 6,
      version: 2,
      estado: 'BORRADOR',
    });

    expect(crearBorrador).toHaveBeenCalledWith(
      expect.objectContaining({
        idServicio: 2,
        anio: 2026,
        mes: 6,
        version: 2,
        idUsuarioCreador: 1,
      }),
    );
    expect(existeMes).toHaveBeenCalledWith(2026, 6);
  });

  it('should reject when the target month calendar was not generated by SISTEMA yet', async () => {
    jest.useFakeTimers().setSystemTime(new Date('2026-06-01T12:00:00.000Z'));

    const repository: PlanificacionRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      obtenerNombreServicio: jest.fn().mockResolvedValue('Emergencias'),
      obtenerNombreDepartamento: jest.fn().mockResolvedValue('Enfermeria'),
      existeUsuario: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnServicio: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnDepartamento: jest.fn().mockResolvedValue(true),
      existePlanificacionActivaPeriodo: jest.fn().mockResolvedValue(false),
      obtenerSiguienteVersion: jest.fn().mockResolvedValue(2),
      crearBorrador: jest.fn(),
      cambiarEstado: jest.fn(),
      eliminarLogico: jest.fn(),
      publicar: jest.fn(),
      cerrar: jest.fn(),
    };

    const asegurarMes = jest.fn();
    const calendarioRepository: CalendarioRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      existeMes: jest.fn().mockResolvedValue(false),
      asegurarAnio: jest.fn(),
      asegurarMes,
    };

    const useCase = new CrearBorradorPlanificacionUseCase(
      repository,
      calendarioRepository,
    );

    await expect(
      useCase.execute({
        idServicio: 2,
        anio: 2026,
        mes: 6,
        idUsuarioCreador: 1,
      }),
    ).rejects.toBeInstanceOf(BadRequestException);

    expect(asegurarMes).not.toHaveBeenCalled();
  });

  it('should throw when servicio does not exist', async () => {
    const repository: PlanificacionRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      obtenerNombreServicio: jest.fn().mockResolvedValue(null),
      obtenerNombreDepartamento: jest.fn().mockResolvedValue('Enfermeria'),
      existeUsuario: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnServicio: jest.fn().mockResolvedValue(true),
      existePersonalActivoEnDepartamento: jest.fn().mockResolvedValue(true),
      existePlanificacionActivaPeriodo: jest.fn(),
      obtenerSiguienteVersion: jest.fn(),
      crearBorrador: jest.fn(),
      cambiarEstado: jest.fn(),
      eliminarLogico: jest.fn(),
      publicar: jest.fn(),
      cerrar: jest.fn(),
    };

    const calendarioRepository: CalendarioRepository = {
      listar: jest.fn(),
      obtenerPorId: jest.fn(),
      existeMes: jest.fn(),
      asegurarAnio: jest.fn(),
      asegurarMes: jest.fn(),
    };

    const useCase = new CrearBorradorPlanificacionUseCase(
      repository,
      calendarioRepository,
    );

    await expect(
      useCase.execute({
        idServicio: 999,
        anio: 2026,
        mes: 6,
        idUsuarioCreador: 1,
      }),
    ).rejects.toBeInstanceOf(NotFoundException);
  });
});
